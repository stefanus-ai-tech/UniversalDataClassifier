const $ = (selector) => document.querySelector(selector);
let currentRun = null;
let offset = 0;
let pageTotal = 0;
let timer = null;

function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
}
function fmt(value) { return typeof value === 'number' ? value.toLocaleString() : (value ?? '—'); }
function toast(message) { const box=$('#toast'); box.textContent=message; box.classList.remove('hidden'); setTimeout(()=>box.classList.add('hidden'),5000); }
async function api(path, options={}) {
  const response = await fetch(path, options);
  let data;
  try { data = await response.json(); } catch { data = {}; }
  if (!response.ok) throw new Error(data.detail || `Request failed (${response.status})`);
  return data;
}
function showSection(id) { $(`#${id}`).classList.remove('hidden'); }
function statusClass(status) { return status==='AUTO_APPROVED'?'auto':status==='NEEDS_REVIEW'?'review':'unresolved'; }
function metric(label,value,tone='') { return `<div class="metric ${tone}"><span>${escapeHtml(label)}</span><strong>${escapeHtml(fmt(value))}</strong></div>`; }

async function init() {
  try {
    const config = await api('/api/config');
    $('#contract').innerHTML = '<option value="" disabled selected>Choose a classifier</option>'+config.contracts.map(c=>`<option value="${escapeHtml(c.id)}">${escapeHtml(c.name)}</option>`).join('');
    $('#service-status').innerHTML = `<span class="${config.groq_configured?'on':''}"><i></i>Groq ${config.groq_configured?'ready':'off'}</span><span class="${config.laya.reachable?'on':''}"><i></i>Laya ${config.laya.reachable?'ready':config.laya.configured?'offline':'demo mode'}</span>`;
    if(config.laya.configured && !config.laya.reachable) toast(config.laya.message);
  } catch(e) { toast(e.message); }
  const saved = new URLSearchParams(location.search).get('run');
  if(saved) { try { currentRun=await api(`/api/runs/${saved}`); renderRun(currentRun); if(currentRun.status==='RUNNING') startPolling(); } catch {} }
}

$('#file').addEventListener('change', e=>$('#file-name').textContent=e.target.files[0]?.name || 'No file selected');
const drop=$('#dropzone');
drop.addEventListener('dragover',e=>{e.preventDefault();drop.classList.add('dragover')});
drop.addEventListener('dragleave',()=>drop.classList.remove('dragover'));
drop.addEventListener('drop',e=>{e.preventDefault();drop.classList.remove('dragover');if(e.dataTransfer.files.length){$('#file').files=e.dataTransfer.files;$('#file-name').textContent=e.dataTransfer.files[0].name}});
$('#intake-form').addEventListener('submit', async e=>{
  e.preventDefault();
  const button=$('#analyze-button'); button.disabled=true; button.firstChild.textContent='Analyzing… ';
  try {
    const form=new FormData(e.target);
    currentRun=await api('/api/intake',{method:'POST',body:form});
    history.replaceState(null,'',`?run=${currentRun.id}`);
    renderRun(currentRun);
    $('#discovery').scrollIntoView({behavior:'smooth'});
  } catch(err) { toast(err.message); }
  finally { button.disabled=false; button.firstChild.textContent='Analyze dataset '; }
});

function renderRun(run) {
  showSection('discovery'); showSection('pipeline');
  $('#source-name').textContent=run.profile.filename;
  $('#contract-warning').textContent=run.contract_warning||'';
  $('#contract-warning').classList.toggle('hidden',!run.contract_warning);
  const p=run.profile;
  $('#profile-metrics').innerHTML=metric('Records',p.records)+metric('Fields',p.field_count)+metric('Exact duplicates',p.duplicate_count,'amber')+metric('Malformed',p.malformed_count,p.malformed_count?'red':'teal');
  $('#fields-table').innerHTML=p.columns.map(c=>`<tr><td>${escapeHtml(c.name)}</td><td>${escapeHtml(c.type)}</td><td>${c.missing_pct}%</td></tr>`).join('');
  $('#sample-record').textContent=JSON.stringify(p.samples[0]||{},null,2);
  $('#plan-origin').textContent=`Generated by ${run.plan.generated_by.replaceAll('_',' ')}${run.plan.fallback_reason?' · '+run.plan.fallback_reason:''}`;
  $('#plan-operations').innerHTML=run.plan.operations.map((op,i)=>`<label class="operation"><input type="checkbox" data-index="${i}" checked ${run.status==='READY'?'':'disabled'}><span>${escapeHtml(op.field)}</span><code>${escapeHtml(op.op)}</code></label>`).join('') || '<span class="small-note">No transformations needed.</span>';
  $('#run-button').disabled=run.status!=='READY';
  $('#run-status').textContent=run.status;
  updateProgress(run);
  if(run.status==='COMPLETE') renderResults(run);
  if(run.status==='FAILED') toast(run.error||'Pipeline failed');
}
$('#run-button').addEventListener('click',async()=>{
  if(!currentRun) return;
  const selected=[...$('#plan-operations').querySelectorAll('input:checked')].map(el=>currentRun.plan.operations[Number(el.dataset.index)]);
  try {
    currentRun=await api(`/api/runs/${currentRun.id}/plan`,{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({...currentRun.plan,operations:selected})});
    await api(`/api/runs/${currentRun.id}/execute`,{method:'POST'});
    $('#run-button').disabled=true;
    startPolling();
    $('#pipeline').scrollIntoView({behavior:'smooth'});
  } catch(err) { toast(err.message); }
});
function startPolling(){if(timer)clearInterval(timer);timer=setInterval(async()=>{try{currentRun=await api(`/api/runs/${currentRun.id}`);$('#run-status').textContent=currentRun.status;updateProgress(currentRun);if(['COMPLETE','FAILED'].includes(currentRun.status)){clearInterval(timer);timer=null;renderRun(currentRun)}}catch(err){clearInterval(timer);toast(err.message)}},1200)}
function updateProgress(run){
  const processed=run.metrics?.processed||0, total=run.metrics?.input||1;
  const retrying=run.stage==='retrying_laya';
  const pct=run.status==='COMPLETE'?100:run.status==='READY'?12:retrying?Math.max(15,Math.min(98,Math.round((run.metrics.retry_processed||0)/(run.metrics.retry_total||1)*100))):Math.max(15,Math.min(98,Math.round(processed/total*100)));
  $('#progress-bar').style.width=`${pct}%`;
  $('#progress-text').textContent=run.status==='COMPLETE'?`Completed · ${fmt(processed)} records processed`:run.status==='FAILED'?run.error:run.status==='READY'?'Cleaning plan ready for review.':retrying?`${fmt(run.metrics.retry_processed||0)} / ${fmt(run.metrics.retry_total||0)} Laya decisions retried`:`${fmt(processed)} / ${fmt(total)} records · ${run.stage.replaceAll('_',' ')}`;
  const done=run.status==='COMPLETE'?5:run.status==='READY'?1:run.stage==='cleaning'?2:3;
  [...$('#steps').children].forEach((step,i)=>{step.classList.toggle('done',i<done);step.querySelector('span').textContent=i<done?'complete':run.status==='RUNNING'&&i===done?'running':'waiting'});
}
function renderResults(run){
  showSection('explorer'); showSection('exports');
  const s=run.summary, c=s.counts||{};
  $('#result-metrics').innerHTML=metric('Processed',run.metrics.processed)+metric('Auto approved',c.AUTO_APPROVED||0,'teal')+metric('Needs review',c.NEEDS_REVIEW||0,'amber')+metric('Unresolved',c.UNRESOLVED||0,'red');
  const labels=Object.entries(s.labels||{}), max=Math.max(1,...labels.map(x=>x[1]));
  $('#label-chart').innerHTML=labels.map(([label,count])=>`<div class="bar-row"><span>${escapeHtml(label)}</span><div class="bar-track"><div style="width:${count/max*100}%"></div></div><b>${count}</b></div>`).join('')||'<p class="small-note">No results.</p>';
  $('#engine-chart').innerHTML=Object.entries(s.engines||{}).map(([name,count])=>`<div class="engine-row"><span>${escapeHtml(name.replaceAll('_',' '))}</span><b>${count}</b></div>`).join('');
  $('#retry-laya').classList.toggle('hidden',!(s.engines?.laya_error>0));
  for(const type of ['xlsx','csv','json']) $('#export-'+type).href=`/api/runs/${run.id}/export/${type}`;
  loadRecords();
}
$('#retry-laya').addEventListener('click',async()=>{if(!currentRun)return;try{await api(`/api/runs/${currentRun.id}/retry-laya`,{method:'POST'});$('#retry-laya').classList.add('hidden');startPolling()}catch(err){toast(err.message)}});
async function loadRecords(){
  if(!currentRun) return;
  const filter=$('#review-filter').value;
  try{
    const page=await api(`/api/runs/${currentRun.id}/records?offset=${offset}&limit=25&review=${encodeURIComponent(filter)}`);
    pageTotal=page.total;
    $('#record-count').textContent=`${fmt(page.total)} results`;
    $('#records-table').innerHTML=page.records.map((r,i)=>`<tr data-index="${i}"><td>${escapeHtml(r.record_id)}</td><td>${escapeHtml(r.decision.label||'—')}</td><td><span class="status-tag ${statusClass(r.review.status)}">${escapeHtml(r.review.status.replaceAll('_',' '))}</span></td></tr>`).join('') || '<tr><td colspan="3">No records found.</td></tr>';
    $('#records-table').querySelectorAll('tr[data-index]').forEach(row=>row.addEventListener('click',()=>showRecord(page.records[Number(row.dataset.index)])));
    $('#page-label').textContent=`${Math.floor(offset/25)+1} / ${Math.max(1,Math.ceil(page.total/25))}`;
    $('#prev-page').disabled=offset===0;$('#next-page').disabled=offset+25>=page.total;
    if(page.records.length) showRecord(page.records[0]);
  }catch(err){toast(err.message)}
}
function showRecord(r){
  const confidence=r.decision.confidence==null?'No calibrated confidence':`${Math.round(r.decision.confidence*100)}% confidence`;
  $('#record-detail').innerHTML=`<div class="trace-head"><h4>${escapeHtml(r.record_id)}</h4><span class="status-tag ${statusClass(r.review.status)}">${escapeHtml(r.review.status.replaceAll('_',' '))}</span></div>
    <div class="trace-block"><h5>SOURCE · ROW ${r.row_number}</h5><pre>${escapeHtml(JSON.stringify(r.raw_data,null,2))}</pre></div>
    <div class="trace-block"><h5>CLEANED DATA</h5><pre>${escapeHtml(JSON.stringify(r.cleaned_data,null,2))}</pre></div>
    <div class="trace-block"><h5>SEMANTIC STATE & EVIDENCE</h5><pre>${escapeHtml(JSON.stringify({facts:r.semantic_state,evidence:r.evidence},null,2))}</pre></div>
    <div class="trace-block"><h5>DECISION</h5><span class="trace-decision">${escapeHtml(r.decision.label||'Unresolved')}</span><span class="trace-meta">${escapeHtml(r.decision.engine)} · ${confidence}</span>${r.decision.error?`<p class="decision-error">${escapeHtml(r.decision.error)}</p>`:''}<pre>${escapeHtml(JSON.stringify(r.decision.alternatives,null,2))}</pre></div>
    <div class="trace-block"><h5>POLICY & API SIMULATION</h5><pre>${escapeHtml(JSON.stringify(r.action,null,2))}</pre></div>`;
}
$('#review-filter').addEventListener('change',()=>{offset=0;loadRecords()});
$('#prev-page').addEventListener('click',()=>{offset=Math.max(0,offset-25);loadRecords()});
$('#next-page').addEventListener('click',()=>{if(offset+25<pageTotal){offset+=25;loadRecords()}});
document.querySelectorAll('.nav-link').forEach(link=>link.addEventListener('click',e=>{const target=$('#'+link.dataset.target);if(target.classList.contains('hidden')){e.preventDefault();toast('Analyze a dataset first.');return}document.querySelectorAll('.nav-link').forEach(l=>l.classList.remove('active'));link.classList.add('active')}));
init();
